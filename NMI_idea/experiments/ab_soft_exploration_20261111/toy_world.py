"""Small public-only toy world for the soft-exploration pressure test.

The module is deliberately self-contained.  A runner may use ``kernel`` for
exact finite-state planning, or ``sample_step`` for a coupled simulation.  No
function takes a target side, recovery flag, or any other hidden renderer
variable from a policy; those values live only in the eight latent states and
the returned transition/emission matrices.

Latent-state order
------------------
``latent_index(h, permanent, present)`` uses the following stable order:

``h`` is ``L`` then ``R``; within a side, ``permanent`` is false then true;
within that, ``present`` is false then true.  Thus the integer index is
``h_index * 4 + int(permanent) * 2 + int(present)``.  A row of ``transition``
is an old state and a column is a post-frame state.  Both emission matrices
are indexed by that post-frame state and have five public outcomes:

* ``0``: miss;
* ``1 + 2*q + i``: quality-pass bit ``q`` and identity-match bit ``i``.

``target_emission`` is the target-detection contribution: outcome ``0`` is
always zero and outcomes ``1..4`` have total mass ``.80`` only when the
post-transition target is present, on the action side, and visible.  The
ordinary ``emission`` is the actual public distribution,
``target_detect_mass + (1-target_detect_mass)*clutter_distribution``.  Thus a
visible target miss and a shadowed target both leave the ``.10`` clutter
channel available.  This keeps target and clutter likelihoods inspectable
without exposing the latent branch to a policy.
"""

from __future__ import annotations

from dataclasses import dataclass
import numpy as np


N_STATES = 8
N_OBSERVATIONS = 5
NODES = ("C", "EL", "ER", "TL", "TR")
KINDS = ("move", "peek", "scan")
SIDES = ("L", "R")


def _canonical_side(side: str | None) -> str | None:
    if side is None:
        return None
    value = str(side).strip().upper()
    aliases = {"LEFT": "L", "RIGHT": "R"}
    value = aliases.get(value, value)
    if value not in SIDES:
        raise ValueError(f"side must be L/R/None, got {side!r}")
    return value


def _canonical_node(node: str) -> str:
    value = str(node).strip().upper()
    if value not in NODES:
        raise ValueError(f"unknown node {node!r}; expected one of {NODES}")
    return value


@dataclass(frozen=True)
class Fixture:
    """Public fixture geometry.

    ``shadow`` is ``None``, ``"L"``/``"left"``, or ``"R"``/``"right"``.
    ``narrow=False`` adds the direct ``EL <-> ER`` edge; ``narrow=True``
    leaves only the base graph edges.
    """

    shadow: str | None = None
    narrow: bool = False

    def __post_init__(self) -> None:
        shadow = None if self.shadow in (None, "", "none", "None") else _canonical_side(self.shadow)
        object.__setattr__(self, "shadow", shadow)
        object.__setattr__(self, "narrow", bool(self.narrow))


@dataclass(frozen=True)
class Action:
    """One legal frame action.

    ``name`` is a stable public identifier.  Actions generated by
    ``legal_actions`` use ``move_<source>_to_<dest>`` for moves and
    ``peek_<node>``/``scan_<node>`` for in-place captures.  ``side`` is the
    sensing side, not a hidden target-side argument.
    """

    name: str
    dest: str
    kind: str
    side: str | None

    def __post_init__(self) -> None:
        object.__setattr__(self, "name", str(self.name))
        object.__setattr__(self, "dest", _canonical_node(self.dest))
        kind = str(self.kind).strip().lower()
        if kind not in KINDS:
            raise ValueError(f"kind must be one of {KINDS}, got {self.kind!r}")
        object.__setattr__(self, "kind", kind)
        object.__setattr__(self, "side", _canonical_side(self.side))


def latent_index(h: str | int, permanent: bool, present: bool) -> int:
    """Return the stable latent-state index for hidden ``(h,z,m)``."""

    if isinstance(h, (int, np.integer)) and not isinstance(h, bool):
        h_index = int(h)
        if h_index not in (0, 1):
            raise ValueError(f"integer h must be 0/1, got {h!r}")
    else:
        side = _canonical_side(str(h))
        h_index = 0 if side == "L" else 1
    return h_index * 4 + int(bool(permanent)) * 2 + int(bool(present))


def _decode_state(state: int) -> tuple[str, bool, bool]:
    if not isinstance(state, (int, np.integer)) or isinstance(state, bool) or not 0 <= int(state) < N_STATES:
        raise ValueError(f"state must be an integer in [0, {N_STATES}), got {state!r}")
    value = int(state)
    h = "L" if value < 4 else "R"
    local = value % 4
    permanent = bool(local // 2)
    present = bool(local % 2)
    return h, permanent, present


def prior() -> np.ndarray:
    """Return the independent prior over the eight latent states.

    ``P(h=L)=P(h=R)=.5``, ``P(permanent)=.1``, and
    ``P(present)=.2``.  The true simulation initial mode is intentionally not
    encoded here; the caller can use ``latent_index(h, z, False)`` for the
    specified lost initial state.
    """

    values = np.zeros(N_STATES, dtype=np.float64)
    for state in range(N_STATES):
        _h, permanent, present = _decode_state(state)
        values[state] = 0.5 * (0.1 if permanent else 0.9) * (0.2 if present else 0.8)
    return values


def _node_side(node: str) -> str | None:
    if node in ("EL", "TL"):
        return "L"
    if node in ("ER", "TR"):
        return "R"
    return None


def _neighbors(node: str, fixture: Fixture) -> tuple[str, ...]:
    base = {
        "C": ("EL", "ER"),
        "EL": ("C", "TL"),
        "ER": ("C", "TR"),
        "TL": ("EL",),
        "TR": ("ER",),
    }
    if not fixture.narrow:
        if node == "EL":
            base["EL"] = ("C", "TL", "ER")
        elif node == "ER":
            base["ER"] = ("C", "TR", "EL")
    return base[node]


def _edge_side(source: str, dest: str) -> str | None:
    # Each move captures at its destination.  C has no sensing side/target.
    return _node_side(dest)


def legal_actions(node: str, fixture: Fixture) -> tuple[Action, ...]:
    """Return deterministic legal frame actions from ``node``.

    Moves come first in graph-neighbor order, followed by ``peek`` and
    ``scan`` for E/T nodes.  Each action consumes exactly one frame.
    """

    source = _canonical_node(node)
    if not isinstance(fixture, Fixture):
        raise TypeError("fixture must be a Fixture")
    actions = [
        Action(
            name=f"move_{source}_to_{dest}",
            dest=dest,
            kind="move",
            side=_edge_side(source, dest),
        )
        for dest in _neighbors(source, fixture)
    ]
    side = _node_side(source)
    if side is not None:
        actions.extend(
            (
                Action(name=f"peek_{source}", dest=source, kind="peek", side=side),
                Action(name=f"scan_{source}", dest=source, kind="scan", side=side),
            )
        )
    return tuple(actions)


def _shadow_blocks(action: Action, fixture: Fixture) -> bool:
    """Whether ordinary E-side movement/scan is blocked by the fixture."""

    if fixture.shadow is None or action.side != fixture.shadow or action.kind not in ("move", "scan"):
        return False
    shadow_node = "EL" if fixture.shadow == "L" else "ER"
    # Capture is taken at the destination/terminal point.  Leaving the
    # shadow-side E therefore is not blocked; entering that E is.  T is
    # deliberately unshadowed.
    return action.dest == shadow_node


def _recovery_probability(h: str, present: bool, permanent: bool, action: Action) -> float:
    if permanent:
        return 0.0
    if present:
        return 0.0
    if action.side != h:
        return 0.10
    if action.kind == "peek":
        return 0.90
    if action.kind in ("scan", "move"):
        return 0.70
    return 0.10


def _target_physical(h: str, present: bool, action: Action) -> bool:
    # C is a transit node with no target coverage.  Moves are sensed at their
    # destination, so only E/T destinations (or their in-place captures) can
    # carry the side-specific target channel.
    return bool(present and action.dest != "C" and action.side is not None and action.side == h)


def _target_visible(h: str, present: bool, action: Action, fixture: Fixture) -> bool:
    return _target_physical(h, present, action) and not _shadow_blocks(action, fixture)


def _qid_distribution(quality_pass: float, identity_match: float) -> np.ndarray:
    """Four-category quality/identity distribution, ordered by outcome 1..4."""

    q = float(quality_pass)
    identity = float(identity_match)
    values = np.zeros(4, dtype=np.float64)
    values[0] = (1.0 - q) * (1.0 - identity)
    values[1] = (1.0 - q) * identity
    values[2] = q * (1.0 - identity)
    values[3] = q * identity
    return values


def _emission_rows(action: Action, fixture: Fixture, state: int) -> tuple[np.ndarray, np.ndarray]:
    h, _permanent, present = _decode_state(state)
    physical_target = _target_physical(h, present, action)
    visible_target = _target_visible(h, present, action, fixture)

    target_mass = 0.80 if visible_target else 0.0
    target_qid = _qid_distribution(0.95, 0.90)
    clutter = np.r_[0.90, 0.10 * _qid_distribution(0.70, 0.10)]
    # target_emission[0] is intentionally zero: it records only detected
    # target contribution, not the target detector's missed mass.
    target = np.r_[0.0, target_mass * target_qid]
    actual = np.zeros(N_OBSERVATIONS, dtype=np.float64)
    actual[0] = (1.0 - target_mass) * clutter[0]
    actual[1:] = target[1:] + (1.0 - target_mass) * clutter[1:]
    return actual, target


def kernel(action: Action, fixture: Fixture) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return ``(transition, emission, target_emission)`` for one action.

    ``transition[old, new]`` is the pre-capture mode transition.  The two
    emission matrices are indexed by ``new`` and public outcome ``0..4``.
    ``fixture.shadow`` affects sensing only; recovery dynamics follow the
    action's public side/kind exactly as specified.
    """

    if not isinstance(action, Action):
        raise TypeError("action must be an Action")
    if not isinstance(fixture, Fixture):
        raise TypeError("fixture must be a Fixture")

    transition = np.zeros((N_STATES, N_STATES), dtype=np.float64)
    emission = np.zeros((N_STATES, N_OBSERVATIONS), dtype=np.float64)
    target_emission = np.zeros((N_STATES, N_OBSERVATIONS), dtype=np.float64)
    for old in range(N_STATES):
        h, permanent, present = _decode_state(old)
        p_present = 0.0 if permanent else (0.97 if present else _recovery_probability(h, present, permanent, action))
        new_present = latent_index(h, permanent, True)
        new_lost = latent_index(h, permanent, False)
        transition[old, new_present] = p_present
        transition[old, new_lost] = 1.0 - p_present
    for new in range(N_STATES):
        actual, target = _emission_rows(action, fixture, new)
        emission[new] = actual
        target_emission[new] = target

    # Keep the public contract numerical and exact to floating point roundoff.
    transition /= transition.sum(axis=1, keepdims=True)
    emission /= emission.sum(axis=1, keepdims=True)
    return transition, emission, target_emission


def _unit_uniform(value: float, name: str) -> float:
    value = float(value)
    if not 0.0 <= value <= 1.0:
        raise ValueError(f"{name} must be in [0, 1], got {value!r}")
    return value


def _draw_categorical(probabilities: np.ndarray, uniform: float) -> int:
    cdf = np.cumsum(probabilities, dtype=np.float64)
    # searchsorted(..., side='right') makes u=0 choose the first positive bin
    # and u=1 choose the final bin after clipping.
    return int(min(np.searchsorted(cdf, uniform, side="right"), len(probabilities) - 1))


def sample_step(
    state: int,
    action: Action,
    fixture: Fixture,
    u_trans: float,
    u_obs: float,
    u_assoc: float,
) -> tuple[int, int, bool]:
    """Sample one frame using caller-provided common-random-number uniforms.

    The transition is applied before sensing.  ``u_trans`` selects the
    post-frame latent state.  ``u_obs`` selects the public outcome from the
    full T/E mixture.  Conditional on that outcome, ``u_assoc`` selects the
    target association with probability
    ``target_emission[state, obs] / emission[state, obs]``.  This is the
    common-capture-index T/E association convention used by the public
    program-value evaluator.  The returned ``is_target`` is true only for a
    detected target-generated category (target emission has no outcome-0 mass).
    """

    u_trans = _unit_uniform(u_trans, "u_trans")
    u_obs = _unit_uniform(u_obs, "u_obs")
    u_assoc = _unit_uniform(u_assoc, "u_assoc")
    _decode_state(state)
    transition, emission, target_emission = kernel(action, fixture)
    next_state = _draw_categorical(transition[int(state)], u_trans)
    observation = _draw_categorical(emission[next_state], u_obs)
    likelihood = float(emission[next_state, observation])
    target_likelihood = float(target_emission[next_state, observation])
    # Multiplication form is intentional: it is the exact paired-CRN rule
    # used by the public program-value evaluator.
    return next_state, observation, bool(u_assoc * likelihood < target_likelihood)


